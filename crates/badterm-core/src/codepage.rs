//! The code pages behind CTerm's built-in fonts (IDs 1-31): what a byte in
//! one is as Unicode, and back, for typing, pasting and copying text when
//! the BBS shows its screen in one of them. Bytes below 0x80 are ASCII in
//! all of them. Generated from Python's codec tables; haik8 (7), ARMSCII-8
//! (15) and CP1131 (31) aren't among them, and stay CP437.

/// A code page's upper half: the character each byte 0x80-0xFF is.
#[derive(Debug)]
pub struct CodePage {
    pub name: &'static str,
    upper: [char; 128],
}

impl CodePage {
    /// A byte as Unicode (control bytes below 0x20 aren't characters here).
    pub fn decode(&self, b: u8) -> char {
        if b < 0x80 { b as char } else { self.upper[(b - 0x80) as usize] }
    }

    /// A character as a byte of this code page, if it has one.
    pub fn encode(&self, c: char) -> Option<u8> {
        if (c as u32) < 0x80 {
            return Some(c as u8);
        }
        self.upper.iter().position(|&u| u == c).map(|i| 0x80 + i as u8)
    }

    pub fn encode_str(&self, s: &str) -> Vec<u8> {
        s.chars().map(|c| self.encode(c).unwrap_or(b'?')).collect()
    }
}

/// The code page a CTerm font ID shows, if BadTerm knows it.
pub fn for_font(id: u8) -> Option<&'static CodePage> {
    Some(match id {
        1 | 20 => &CP1251,
        2 | 12 | 22 => &KOI8_R,
        3 => &ISO_8859_2,
        4 | 11 | 13 | 23 => &ISO_8859_4,
        5 | 25 | 27 => &CP866,
        6 => &ISO_8859_9,
        8 => &ISO_8859_8,
        9 => &KOI8_U,
        10 | 16 => &ISO_8859_15,
        14 => &ISO_8859_5,
        17 | 18 => &CP850,
        19 | 28 => &CP865,
        21 => &ISO_8859_7,
        24 | 30 => &ISO_8859_1,
        29 => &CP866U,
        _ => return None,
    })
}

