#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cyrillic_both_ways() {
        let cp866 = for_font(25).unwrap();
        assert_eq!(cp866.encode_str("Привет!"), [0x8F, 0xE0, 0xA8, 0xA2, 0xA5, 0xE2, b'!']);
        assert_eq!(cp866.decode(0x8F), 'П');
        let koi = for_font(2).unwrap();
        assert_eq!(koi.encode_str("Да"), [0xE4, 0xC1]);
        assert_eq!(koi.decode(0xC1), 'а');
        // Not in the code page: a question mark.
        assert_eq!(for_font(21).unwrap().encode_str("Ω€Ж"), [0xD9, 0xA4, b'?']);
        assert!(for_font(7).is_none() && for_font(0).is_none());
    }
}
